#!/usr/bin/env python3
"""Generate mc/encodings.s: one line per 8008 instruction with its expected
encoding, computed from the octal fields of the MCS-8 manual's instruction
summary (spec/isa.md), independently of the TableGen definitions."""
import os

R = "abcdehl"            # register field 0..6; 7 = m
ALU = ["ad", "ac", "su", "sb", "nd", "xr", "or", "cp"]
COND = "czsp"
lines = []


def ins(text, *octs):
    lines.append((text, ["0x%02x" % o for o in octs]))


for d in range(7):
    for s in range(7):
        ins("l%s%s" % (R[d], R[s]), 0o300 | d << 3 | s)
    ins("l%sm" % R[d], 0o307 | d << 3)
    ins("lm%s" % R[d], 0o370 | d)
    ins("l%si 0x5a" % R[d], 0o006 | d << 3, 0x5A)
    if d:
        ins("in%s" % R[d], 0o000 | d << 3)
        ins("dc%s" % R[d], 0o001 | d << 3)
ins("lmi 0xa5", 0o076, 0xA5)
for o, a in enumerate(ALU):
    for s in range(7):
        ins(a + R[s], 0o200 | o << 3 | s)
    ins(a + "m", 0o207 | o << 3)
    ins(a + "i 0x7f", 0o004 | o << 3, 0x7F)
for i, r in enumerate(["rlc", "rrc", "ral", "rar"]):
    ins(r, 0o002 | i << 3)
ins("jmp 0x1234", 0o104, 0x34, 0x12)
ins("cal 0x3fff", 0o106, 0xFF, 0x3F)
ins("ret", 0o007)
for c, cn in enumerate(COND):
    ins("jf%s 0x0102" % cn, 0o100 | c << 3, 0x02, 0x01)
    ins("jt%s 0x0102" % cn, 0o140 | c << 3, 0x02, 0x01)
    ins("cf%s 0x0102" % cn, 0o102 | c << 3, 0x02, 0x01)
    ins("ct%s 0x0102" % cn, 0o142 | c << 3, 0x02, 0x01)
    ins("rf%s" % cn, 0o003 | c << 3)
    ins("rt%s" % cn, 0o043 | c << 3)
for n in range(8):
    ins("rst %d" % n, 0o005 | n << 3)
for p in range(8):
    ins("inp %d" % p, 0o101 | p << 1)
for p in range(8, 32):
    ins("out %d" % p, 0o101 | p << 1)
ins("hlt", 0o000)

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "encodings.s")
with open(out, "w", newline="\n") as f:
    f.write("# Generated by gen_encodings.py from the MCS-8 instruction summary.\n")
    f.write("# RUN: llvm-mc -triple i8008 -show-encoding %s | FileCheck %s\n\n")
    for text, enc in lines:
        f.write("%s\n# CHECK: %s ; encoding: [%s]\n" % (text, text.replace(" ", "{{[[:space:]]+}}", 1), ",".join(enc)))
print("%d instructions" % len(lines))

# Disassembly: every encoding above decodes back to its mnemonic.
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "disasm.txt")
with open(out, "w", newline="\n") as f:
    f.write("# Generated by gen_encodings.py from the MCS-8 instruction summary.\n")
    f.write("# RUN: llvm-mc -triple i8008 --disassemble %s | FileCheck %s\n\n")
    for text, enc in lines:
        f.write("%s\n# CHECK: %s\n" % (" ".join(enc), text.replace(" ", "{{[[:space:]]+}}", 1)))

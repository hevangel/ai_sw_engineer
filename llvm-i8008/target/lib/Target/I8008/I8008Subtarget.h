#ifndef LLVM_LIB_TARGET_I8008_I8008SUBTARGET_H
#define LLVM_LIB_TARGET_I8008_I8008SUBTARGET_H

#include "I8008FrameLowering.h"
#include "I8008ISelLowering.h"
#include "I8008InstrInfo.h"
#include "I8008RegisterInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "I8008GenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class I8008Subtarget : public I8008GenSubtargetInfo {
  virtual void anchor();
  I8008InstrInfo InstrInfo;
  I8008TargetLowering TLInfo;
  I8008FrameLowering FrameLowering;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

public:
  I8008Subtarget(const Triple &TT, const std::string &CPU,
                 const std::string &FS, const TargetMachine &TM);
  ~I8008Subtarget() override;

  I8008Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  // Auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const I8008InstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const I8008RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const I8008TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;

  void initLibcallLoweringInfo(LibcallLoweringInfo &Info) const override;
};

} // end namespace llvm

#endif

#ifndef LLVM_LIB_TARGET_I4004_I4004SUBTARGET_H
#define LLVM_LIB_TARGET_I4004_I4004SUBTARGET_H

#include "I4004FrameLowering.h"
#include "I4004ISelLowering.h"
#include "I4004InstrInfo.h"
#include "I4004RegisterInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "I4004GenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class I4004Subtarget : public I4004GenSubtargetInfo {
  virtual void anchor();
  I4004InstrInfo InstrInfo;
  I4004TargetLowering TLInfo;
  I4004FrameLowering FrameLowering;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

public:
  I4004Subtarget(const Triple &TT, const std::string &CPU,
                 const std::string &FS, const TargetMachine &TM);
  ~I4004Subtarget() override;

  I4004Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  // Auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const I4004InstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const I4004RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const I4004TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;
};

} // end namespace llvm

#endif

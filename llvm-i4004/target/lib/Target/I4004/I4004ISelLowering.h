#ifndef LLVM_LIB_TARGET_I4004_I4004ISELLOWERING_H
#define LLVM_LIB_TARGET_I4004_I4004ISELLOWERING_H

#include "llvm/CodeGen/TargetLowering.h"

namespace llvm {

class I4004Subtarget;
class I4004TargetMachine;

// The I4004ISD::NodeType enum (CALL/RET/WRAPPER) is generated by
// -gen-sd-node-info from I4004InstrCodeGen.td and included via
// I4004GenSDNodeInfo.inc (GET_SDNODE_ENUM) in I4004SelectionDAGInfo.h and
// I4004ISelLowering.cpp.

class I4004TargetLowering : public TargetLowering {
public:
  explicit I4004TargetLowering(const TargetMachine &TM,
                               const I4004Subtarget &STI);

  const char *getTargetNodeName(unsigned Opcode) const override;

  SDValue LowerOperation(SDValue Op, SelectionDAG &DAG) const override;

  SDValue LowerFormalArguments(SDValue Chain, CallingConv::ID CallConv,
                               bool IsVarArg,
                               const SmallVectorImpl<ISD::InputArg> &Ins,
                               const SDLoc &DL, SelectionDAG &DAG,
                               SmallVectorImpl<SDValue> &InVals) const override;

  SDValue LowerReturn(SDValue Chain, CallingConv::ID CallConv, bool IsVarArg,
                      const SmallVectorImpl<ISD::OutputArg> &Outs,
                      const SmallVectorImpl<SDValue> &OutVals, const SDLoc &DL,
                      SelectionDAG &DAG) const override;

  SDValue LowerCall(TargetLowering::CallLoweringInfo &CLI,
                    SmallVectorImpl<SDValue> &InVals) const override;

  SDValue LowerCallResult(SDValue Chain, SDValue InGlue,
                          CallingConv::ID CallConv, bool IsVarArg,
                          const SmallVectorImpl<ISD::InputArg> &Ins,
                          const SDLoc &DL, SelectionDAG &DAG,
                          SmallVectorImpl<SDValue> &InVals) const;

private:
  const I4004Subtarget &Subtarget;

  SDValue LowerGlobalAddress(SDValue Op, SelectionDAG &DAG) const;
};

} // end namespace llvm

#endif

#ifndef LLVM_LIB_TARGET_I4004_MCTARGETDESC_I4004INSTPRINTER_H
#define LLVM_LIB_TARGET_I4004_MCTARGETDESC_I4004INSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class I4004InstPrinter : public MCInstPrinter {
public:
  I4004InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                   const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  // Defined by the TableGen-generated I4004GenAsmWriter.inc.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;

  // Autogenerated by tblgen.
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  // Custom operand printers.
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImm4(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImm8(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printCond(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printAddr8(const MCInst *MI, uint64_t Address, unsigned OpNo,
                  raw_ostream &O);
  void printAddr12(const MCInst *MI, uint64_t Address, unsigned OpNo,
                   raw_ostream &O);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_I4004_MCTARGETDESC_I4004INSTPRINTER_H

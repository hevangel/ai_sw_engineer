; CHECK: jcn 0x2, 0x20 {{.*}}encoding: [0x12,0x20]

; T  (TEST=0)       -> 0x1 -> [0x11,0x20]
        jcn     t, 0x20
; CHECK: jcn 0x1, 0x20 {{.*}}encoding: [0x11,0x20]

; NZ (invert ACC=0) -> 0xc -> [0x1c,0x20]
        jcn     nz, 0x20
; CHECK: jcn 0xc, 0x20 {{.*}}encoding: [0x1c,0x20]


#!/usr/bin/env python3
"""Generate a tiny i4004 ROM test program that exercises ONE libi4004rt helper.

The program loads the given 8-bit inputs into argument pairs, JMS'es the helper,
writes the 8-bit result -- and, for div/mod, the second output too -- to 4002
chip 0 / register 0 main characters (char0 = result low nibble, char1 = result
high nibble, char2/3 = second output), then spins in a self-JUN halt loop. The
rt_test harness runs it on `chips`, reads those characters back, and the caller
compares them against a Rust/host reference (NOT the helper's own output).

SRC pointer for RAM chip0 reg0 char c = byte 0x0c (high nibble [chip:2][reg:2]
= 0, low nibble = char). We store nibbles with FIM P0,<ptr>; SRC P0; LDM/LD;
WRM.

Emitted assembly is printed to stdout; link it with the helper source via
llvm-mc + i4004_pack.py.
"""
import argparse
import sys


def emit_store(char_idx, src_reg_hi, src_reg_lo):
    """Emit asm to store the nibble currently in ACC to RAM chip0 reg0 char_idx.
    Uses P0 (R0:R1) as the SRC pointer. ACC is preserved by stashing in R4 since
    SRC needs a pair load. Caller guarantees R4 is free here."""
    return []


TEMPLATE_HEAD = """; GENERATED by gen_rt_test.py -- do not edit.
; Test stub for {helper}: inputs {inputs}. Writes outputs to RAM0/reg0/chars.
	.section .reset,"ax"
reset:
	jun	start
	.text
start:
"""

TEMPLATE_TAIL = """halt:	jun	halt		; spin forever (harness runs a fixed cycle count)
"""


def store_pair(result_pair, char_lo, char_hi):
    """Store pair result_pair (Rhi:Rlo) to RAM0/reg0 char_lo (low nibble) and
    char_hi (high nibble). result_pair is like 'r2','r3' (hi,lo)."""
    hi, lo = result_pair
    s = []
    # low nibble -> char_lo
    s.append(f"\tfim\tp0, 0x{char_lo:02x}")
    s.append(f"\tsrc\tp0")
    s.append(f"\tld\t{lo}")
    s.append(f"\twrm")
    # high nibble -> char_hi
    s.append(f"\tfim\tp0, 0x{char_hi:02x}")
    s.append(f"\tsrc\tp0")
    s.append(f"\tld\t{hi}")
    s.append(f"\twrm")
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("helper", help="symbol name, e.g. __mulqi3")
    ap.add_argument("--a", type=lambda s: int(s, 0), default=0, help="first i8 arg")
    ap.add_argument("--b", type=lambda s: int(s, 0), default=0, help="second i8 arg")
    ap.add_argument("--two-out", action="store_true",
                    help="helper leaves a second output in P3 (div: remainder); store it too")
    args = ap.parse_args()

    a, b = args.a & 0xff, args.b & 0xff
    lines = [TEMPLATE_HEAD.format(helper=args.helper, inputs=f"a={a} b={b}")]
    body = []
    # load P1 = a, P2 = b
    body.append(f"\tfim\tp1, 0x{a:02x}")
    body.append(f"\tfim\tp2, 0x{b:02x}")
    body.append(f"\tjms\t{args.helper}")
    # store result P1 (R2 hi, R3 lo) -> char0 (lo), char1 (hi)
    body += store_pair(("r2", "r3"), 0x00, 0x01)
    if args.two_out:
        # second output in P3 (R6 hi, R7 lo) -> char2 (lo), char3 (hi)
        body += store_pair(("r6", "r7"), 0x02, 0x03)
    lines.append("\n".join(body) + "\n")
    lines.append(TEMPLATE_TAIL)
    sys.stdout.write("".join(lines))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Run a DOS command on the ai_hw_engineer RTL (PC DOS 1.00 in drive A) and record the screen.

    rtl_oracle.py <Vibm_pc> <reference_dir> <dos.img> <disk_b.img> <command> <out.txt> [<out_disk_b.img>]

Boots the unchanged IBM BIOS and PC DOS 1.00 from <dos.img> as drive A with
<disk_b.img> in drive B, answers the date prompt, types <command> at the A>
prompt, waits for the next A> prompt and writes:

    # lines                       the input hashes and the final CPU state
    > <command>                   what was typed
    | <screen row>                the 25 text rows, trailing blanks removed

When <out_disk_b.img> is given, drive B is saved after the command (CHKDSK
repairs disks, so the disk afterwards is part of the expected result).
The expected output therefore comes from the original CHKDSK on the RTL, never
from this repository's Rust. Run inside the hardware project's Docker image
from scripts/rtl_oracle.sh.
"""
import hashlib
import json
import subprocess
import sys

# IBM PC scan code set 1: the make code of each character we type (shift noted).
SCAN = {
    **{c: s for c, s in zip('1234567890', range(0x02, 0x0C))},
    **{c: s for c, s in zip('qwertyuiop', range(0x10, 0x1A))},
    **{c: s for c, s in zip('asdfghjkl', range(0x1E, 0x27))},
    **{c: s for c, s in zip('zxcvbnm', range(0x2C, 0x33))},
    ' ': 0x39, '-': 0x0C, '.': 0x34, '\n': 0x1C,
}
SHIFTED = {':': 0x27, '*': 0x09, '?': 0x35}
SHIFT = 0x2A


def keys_for(text):
    out = []
    for ch in text:
        if ch in SCAN:
            out += [SCAN[ch], SCAN[ch] | 0x80]
        elif ch in SHIFTED:
            out += [SHIFT, SHIFTED[ch], SHIFTED[ch] | 0x80, SHIFT | 0x80]
        else:
            raise SystemExit(f"cannot type {ch!r} (use lower case)")
    return out


def screen(state):
    ram = bytes.fromhex(state['vram'])
    cols = 80 if state['mode'] & 1 else 40
    start = ((state['crtc'][12] << 8) | state['crtc'][13]) * 2
    rows = []
    for row in range(25):
        line = ''
        for col in range(cols):
            ch = ram[(start + 2 * (row * cols + col)) & 16383]
            line += chr(ch) if 32 <= ch < 127 else ' '
        rows.append(line.rstrip())
    return rows


def sha(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def main():
    binary, reference, dos, disk_b, cmd, out = sys.argv[1:7]
    save = sys.argv[7] if len(sys.argv) > 7 else None
    proc = subprocess.Popen([binary, reference], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            text=True, bufsize=1)

    def command(line):
        proc.stdin.write(line + '\n')
        proc.stdin.flush()
        reply = proc.stdout.readline()
        return json.loads(reply)

    def run_until(pred, what, limit=1_500_000_000):
        while True:
            state = command('RUN 1000000')
            assert not state['fault'] and state['postErrors'] == 0, 'BIOS/CPU diagnostic'
            rows = screen(state)
            if pred(rows):
                return state, rows
            if state['cycles'] > limit:
                raise SystemExit(f'timeout waiting for {what}\n' + '\n'.join(rows))

    def type_text(text):
        for code in keys_for(text):
            command(f'KEY {code}')

    command(f'MOUNT 0 {dos}')
    command(f'MOUNT 1 {disk_b}')
    command('RESET')
    _, rows = run_until(lambda r: any('date' in x.lower() for x in r), 'the date prompt')
    type_text('10-14-81\n')
    _, rows = run_until(lambda r: any(x.startswith('A>') for x in r), 'the first A> prompt')
    # Let the machine settle, then note the screen so the command's output can be told apart.
    state = command('RUN 2000000')
    type_text(cmd + '\n')
    marker = len([x for x in screen(state) if x])
    state, rows = run_until(
        lambda r: len([x for x in r if x]) > marker + 1 and [x for x in r if x][-1].startswith('A>'),
        'the A> prompt after the command')
    state = command('RUN 2000000')
    rows = screen(state)
    r, s = state['registers'], state['segments']
    names = ['ax', 'cx', 'dx', 'bx', 'sp', 'bp', 'si', 'di']
    final = ' '.join(f'{n}={v:04x}' for n, v in zip(names, r))
    final += ' ' + ' '.join(f'{n}={v:04x}' for n, v in zip(['es', 'cs', 'ss', 'ds'], s))
    lines = [
        '# RTL oracle: original PC DOS 1.00 (drive A) running the command below on the ai_hw_engineer RTL.',
        '# Generated by scripts/rtl_oracle.py; do not edit.',
        f'# dos image sha256 {sha(dos)}',
        f'# disk B sha256 before {sha(disk_b)}',
    ]
    if save:
        command(f'SAVE 1 {save}')
        lines.append(f'# disk B sha256 after {sha(save)}')
    lines += [f'# final {final}', f'> {cmd}']
    lines.extend('|' + row for row in rows)
    print(f'recorded after {state["cycles"]} clocks', flush=True)
    proc.stdin.write('QUIT\n')
    proc.stdin.flush()
    proc.wait(timeout=10)
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()

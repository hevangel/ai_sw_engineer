#!/usr/bin/env python3
"""Boot a floppy image on the hardware project's IBM PC RTL and record what happens.

Mounts <image> as drive A on the RTL system build (`Vibm_pc`: the unchanged
IBM BIOS, Cassette BASIC and the RTL 8088 and peripheral chips), powers it on,
runs until a screen row equals <marker>, lets the machine settle, and writes a
transcript in the format `tests/replay.rs` replays (`boot`, `until row`,
`screen`), plus comment lines the replay ignores:

    # image sha256 <hex>        the floppy that was booted
    # final ax=.. cx=.. ...     the CPU registers, segments and the halt state
                                when the screen settled

The expected output therefore comes from the RTL, never from the Rust emulator.
Run inside the hardware project's Docker image, from `scripts/rtl_boot_images.sh`.

    rtl_boot_image.py <Vibm_pc> <reference_dir> <image.img> <marker row> <out.txt>
"""
import hashlib
import json
import subprocess
import sys


def screen(state):
    ram = bytes.fromhex(state['vram'])
    cols = 80 if state['mode'] & 1 else 40
    start = ((state['crtc'][12] << 8) | state['crtc'][13]) * 2
    rows = []
    for row in range(25):
        line = ''
        for col in range(cols):
            ch = ram[(start + 2 * (row * cols + col)) & 16383]
            line += chr(ch) if 32 <= ch < 127 else ' '
        rows.append(line.rstrip())
    return rows


def main():
    binary, reference, image, marker, out = sys.argv[1:6]
    with open(image, 'rb') as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    proc = subprocess.Popen([binary, reference], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            text=True, bufsize=1)

    def command(line):
        proc.stdin.write(line + '\n')
        proc.stdin.flush()
        state = json.loads(proc.stdout.readline())
        assert not state['fault'] and state['postErrors'] == 0, 'BIOS/CPU diagnostic'
        return state

    command(f'MOUNT 0 {image}')
    state = command('RESET')
    limit = 600_000_000
    while True:
        state = command('RUN 1000000')
        if any(r == marker for r in screen(state)):
            break
        if state['cycles'] > limit:
            raise SystemExit(f'timeout waiting for row {marker!r}\n' + '\n'.join(screen(state)))
    state = command('RUN 2000000')
    rows = screen(state)
    assert any(r == marker for r in rows)
    r = state['registers']
    s = state['segments']
    names = ['ax', 'cx', 'dx', 'bx', 'sp', 'bp', 'si', 'di']
    final = ' '.join(f'{n}={v:04x}' for n, v in zip(names, r))
    final += ' ' + ' '.join(f'{n}={v:04x}' for n, v in zip(['es', 'cs', 'ss', 'ds'], s))
    final += f" halted={int(state['halted'])}"
    lines = [
        '# RTL boot transcript: unchanged IBM BIOS, the floppy below as drive A, on the ai_hw_engineer RTL.',
        '# Generated by scripts/rtl_boot_image.py; do not edit.',
        f'# image sha256 {digest}',
        f'# final {final}',
        'boot',
        f'until row {marker}',
        'screen',
    ]
    lines.extend('|' + row for row in rows)
    print(f'recorded after {state["cycles"]} clocks: {final}', flush=True)
    proc.stdin.write('QUIT\n')
    proc.stdin.flush()
    proc.wait(timeout=10)
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()

//! Medium-model proof: code in several 64 KiB segments (far calls), data in segment 0, and a
//! separate 64 KiB far data segment reached through `__far_r8`/`__far_w8` (turned into far
//! loads/stores by the IR pass).
#![no_std]
#![no_main]

mod logic;
#[cfg(feature = "pad")]
mod pad; // generated by scripts/gen_pad.py

extern "C" {
    fn hal_putc(c: u16);
    fn hal_alloc64k() -> u16;
    fn hal_exit() -> !;
    fn __far_r8(seg: u16, off: u16) -> u8;
    fn __far_w8(seg: u16, off: u16, v: u8);
}

struct T;

impl logic::Hal for T {
    fn putc(&mut self, c: u8) {
        unsafe { hal_putc(c as u16) }
    }
    fn far_r8(&mut self, seg: u16, off: u16) -> u8 {
        unsafe { __far_r8(seg, off) }
    }
    fn far_w8(&mut self, seg: u16, off: u16, v: u8) {
        unsafe { __far_w8(seg, off, v) }
    }
}

static SEED: u32 = 0x0BA5_1C00;

#[no_mangle]
pub extern "C" fn main() -> ! {
    let seed = unsafe { core::ptr::read_volatile(&raw const SEED) };
    let seg = unsafe { hal_alloc64k() };
    #[cfg(feature = "pad")]
    let pad: Option<fn(u32) -> u32> = Some(pad::all);
    #[cfg(not(feature = "pad"))]
    let pad: Option<fn(u32) -> u32> = None;
    logic::run(&mut T, seed, seg, pad);
    unsafe { hal_exit() }
}

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    unsafe { hal_exit() }
}

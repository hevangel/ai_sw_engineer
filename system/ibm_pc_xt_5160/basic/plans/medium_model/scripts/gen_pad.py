#!/usr/bin/env python3
"""Writes crate/src/pad.rs: 150 distinct 32-bit functions (about 95 KB of i8086 code) that push
the proof program past one 64 KiB code segment. Deterministic (seed 5)."""
import random
import sys
from pathlib import Path

random.seed(5)
N = 150
out = ["// generated by scripts/gen_pad.py: padding functions\n"]
for k in range(N):
    out.append("#[inline(never)]\npub fn p%d(x: u32) -> u32 {\n    let mut a = x ^ 0x%08x;\n" % (k, random.getrandbits(32)))
    for j in range(10):
        c1 = random.getrandbits(32) | 1
        c2 = random.randrange(1, 31)
        c3 = random.randrange(1, 15)
        op = random.choice([
            "a = a.wrapping_mul(0x%08x).rotate_left(%d) ^ (a >> %d);" % (c1, c2, c3),
            "a = a.wrapping_add(0x%08x) ^ a.rotate_right(%d).wrapping_sub(a << %d);" % (c1, c2, c3),
            "a = if a & 0x%x != 0 { a / %d + 0x%x } else { a %% %d ^ 0x%x };" % (1 << c2, c3 + 2, c1 & 0xffff, c3 + 7, c1 >> 8)])
        out.append("    " + op + "\n")
    out.append("    a\n}\n\n")
out.append("pub fn all(x: u32) -> u32 {\n    let mut s = 0u32;\n")
for k in range(N):
    out.append("    s = s.wrapping_add(p%d(x ^ %d));\n" % (k, k))
out.append("    s\n}\n")
Path(sys.argv[1]).write_text("".join(out))

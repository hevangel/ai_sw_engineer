#!/usr/bin/env python3
"""The linker script of a medium-model program (llvm-i8086/spec/abi.md D10).

    medium_ld.py <segments> > prog.ld

`segments` is the number of far code segments (1 or more; ir_medium.py's `.segments` file
says how many it used). The first segment is the program segment of a PC DOS .EXE (offset
100h up, CS = SS = the PSP, as system/ibm_pc/platform/link_exe_seg.ld): the start code,
segment 0's functions, all data, .bss and the stack (rt/medium/start_far.s). Each far
segment n gets `.far.text.n.*` (the sections ir_medium.py and seg_rt.py name) in a region
of its own (SEGMENT = AUTO). The section .endmark (`__prog_end`) comes last.
"""
import sys

n = int(sys.argv[1])
if n < 1:
    sys.exit("medium_ld.py: at least one far segment")
out = ["/* generated by llvm-i8086/scripts/medium_ld.py %d */" % n, "", "ENTRY(_start)", "", "MEMORY {",
       "  main (rwx) : ORIGIN = 0x0100, LENGTH = 0xFF00"]
for k in range(1, n + 1):
    out.append("  far%d (rwx) : ORIGIN = 0x0000, LENGTH = 0xFFF0, SEGMENT = AUTO" % k)
out += ["}", "", "SECTIONS {",
        "  .text   : { KEEP(*(.text.start)) *(.text .text.*) } > main",
        "  .rodata : { *(.rodata .rodata.*) } > main",
        "  .data   : { *(.data .data.*) } > main",
        "  .bss (NOLOAD) : { *(.bss .bss.*) *(COMMON) } > main"]
for k in range(1, n + 1):
    out.append("  .far%d : { *(.far.text.%d.*) } > far%d" % (k, k, k))
out += ["  .endmark : { KEEP(*(.endmark)) } > far%d" % n, "}", ""]
print("\n".join(out))
